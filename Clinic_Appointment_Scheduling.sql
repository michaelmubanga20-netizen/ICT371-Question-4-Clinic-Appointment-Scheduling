

CREATE TABLE patients(patient_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,full_name text NOT NULL);
CREATE TABLE doctors(doctor_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,full_name text NOT NULL);
CREATE TABLE appointments(
 appointment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 patient_id integer NOT NULL REFERENCES patients(patient_id),
 doctor_id integer NOT NULL REFERENCES doctors(doctor_id),
 appointment_day date NOT NULL,slot_time time NOT NULL,
 status text NOT NULL DEFAULT 'BOOKED' CHECK(status IN('BOOKED','ATTENDED','CANCELLED')),
 CHECK(slot_time IN(TIME '09:00',TIME '10:00',TIME '11:00',TIME '12:00'))
);
CREATE TABLE clinic_summary(
 summary_date date PRIMARY KEY,booked_count bigint NOT NULL,attended_count bigint NOT NULL,cancelled_count bigint NOT NULL
);
